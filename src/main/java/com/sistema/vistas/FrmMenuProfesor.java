    //Metodo para cargar los cursos en la tabla
    private void cargarCursos() {
    List<Curso> todos = ctrlCurso.listarCursos();
    cursosDelProfesor.clear();
    
    // Filtramos por el ID del profesor logueado
    for (Curso c : todos) {
        if (c.getIdProfesor().equals(profesorLogueado.getIdProfesor())) {
            cursosDelProfesor.add(c);
        }
    }

    // Llenamos la tabla
    DefaultTableModel modelo = (DefaultTableModel) tablaCursos.getModel();
    modelo.setRowCount(0);

    for (Curso c : cursosDelProfesor) {
        Object[] fila = new Object[2];
        fila[0] = c.getCodigoCurso();
        fila[1] = c.getNombreCurso();
        modelo.addRow(fila);
    }
}

