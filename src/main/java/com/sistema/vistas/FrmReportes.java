    private void btnModificarAsistenciaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarAsistenciaActionPerformed
       int fila = tablaReportes.getSelectedRow();
    
    // 1. Validar que el usuario haya seleccionado una fila
    if (fila == -1) {
        JOptionPane.showMessageDialog(this, "Por favor, selecciona una fila de la tabla para modificar.", "Aviso", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 2. Obtener el estado NUEVO que el usuario seleccionó en el desplegable de la tabla
    String nuevoEstado = tablaReportes.getValueAt(fila, 3).toString();
    
    // 3. Obtener el objeto original de la lista en memoria
    Asistencia asistenciaOriginal = listaReportesActuales.get(fila);
    
    // 4. Validar si realmente cambió el estado (para no hacer procesos en vano)
    if (nuevoEstado.equals(asistenciaOriginal.getEstado())) {
        JOptionPane.showMessageDialog(this, "El estado no ha cambiado. Selecciona uno diferente si deseas modificarlo.", "Aviso", JOptionPane.INFORMATION_MESSAGE);
        return;
    }

    // 5. Pedir confirmación al usuario
    int confirmacion = JOptionPane.showConfirmDialog(this, 
            "¿Estás seguro de cambiar el estado de este estudiante de '" + asistenciaOriginal.getEstado() + "' a '" + nuevoEstado + "'?", 
            "Confirmar Modificación", 
            JOptionPane.YES_NO_OPTION);

    if (confirmacion == JOptionPane.YES_OPTION) {
        
        // 6. Llamamos al controlador pasándole los datos originales (Carnet, Curso, Fecha)
        boolean modificado = ctrlAsistencia.modificarAsistencia(
                asistenciaOriginal.getIdAsistencia(), 
                asistenciaOriginal.getCarnetEstudiante(), 
                asistenciaOriginal.getCodigoCurso(), 
                asistenciaOriginal.getFecha(), 
                nuevoEstado // Campo modificado
        );
        
        if (modificado) {
            JOptionPane.showMessageDialog(this, "¡Estado modificado correctamente!");
            cargarReportes(); // Refrescamos la tabla para ver el cambio
        } else {
            JOptionPane.showMessageDialog(this, "Error al intentar modificar. Revisa la consola (Output).", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_btnModificarAsistenciaActionPerformed

