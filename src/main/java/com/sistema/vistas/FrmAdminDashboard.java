    // Método para llenar la lista desplegable con los IDs de los profesores
    private void cargarComboBoxProfesores() {
        cmbIdProfesorCurso.removeAllItems();
        ControladorProfesor ctrl = new ControladorProfesor();
        List<Profesor> lista = ctrl.listarProfesores();
        
        for (Profesor p : lista) {
            cmbIdProfesorCurso.addItem(p.getIdProfesor());
        }
    }

