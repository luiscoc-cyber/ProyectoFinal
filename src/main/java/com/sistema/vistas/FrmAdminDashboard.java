// Método para llenar la tabla desde el archivo .txt
    private void cargarTablaEstudiantes() {
        ControladorEstudiante ctrl = new ControladorEstudiante();
        List<Estudiante> lista = ctrl.listarEstudiantes();
        
        // Creamos un modelo para que las celdas NO se puedan editar haciendo doble clic
        DefaultTableModel modelo = new DefaultTableModel(null, new String[]{"Carnet", "Nombre", "Apellido"}) {
            @Override
            public boolean isCellEditable(int row, int column) { return false; }
        };
        
        for (Estudiante est : lista) {
            Object[] fila = { est.getCarnet(), est.getNombre(), est.getApellido() };
            modelo.addRow(fila);
        }
        tblEstudiantes.setModel(modelo);
    }

