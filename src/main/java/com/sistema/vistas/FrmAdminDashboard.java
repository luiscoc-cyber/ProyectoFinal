    private void btnInscribirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInscribirActionPerformed
        // TODO add your handling code here:                                            
        // Validar que haya seleccionado algo
        if (cmbEstudianteInscripcion.getSelectedItem() == null || cmbCursoInscripcion.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un estudiante y un curso.");
            return;
        }

        String carnet = cmbEstudianteInscripcion.getSelectedItem().toString();
        String codigoCurso = cmbCursoInscripcion.getSelectedItem().toString();

        ControladorInscripcion ctrl = new ControladorInscripcion();
        // El controlador ya valida si el estudiante existe, si el curso existe, y si no está repetido
        boolean exito = ctrl.registrarInscripcion(carnet, codigoCurso);
        
        if (exito) {
            JOptionPane.showMessageDialog(this, "¡Inscripción realizada con éxito!");
            cargarTablaInscripciones(); // Refresca la tabla
        } else {
            JOptionPane.showMessageDialog(this, "Error. El estudiante ya está inscrito en este curso o los datos no existen.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnInscribirActionPerformed

    private void btnEliminarInscripcionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarInscripcionActionPerformed
        // TODO add your handling code here:                                                       
        int fila = tblInscripciones.getSelectedRow();
        
        if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione una inscripción de la tabla para eliminarla.");
            return;
        }

        // Sacamos el ID de la inscripción de la fila seleccionada (columna 0)
        String idInscripcion = tblInscripciones.getValueAt(fila, 0).toString();

        int confirmacion = JOptionPane.showConfirmDialog(this, "¿Seguro que desea eliminar esta inscripción?", "Confirmar", JOptionPane.YES_NO_OPTION);
        
        if (confirmacion == JOptionPane.YES_OPTION) {
            ControladorInscripcion ctrl = new ControladorInscripcion();
            if (ctrl.eliminarInscripcion(idInscripcion)) {
                JOptionPane.showMessageDialog(this, "Inscripción eliminada.");
                cargarTablaInscripciones();
            } else {
                JOptionPane.showMessageDialog(this, "Error al eliminar.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnEliminarInscripcionActionPerformed

