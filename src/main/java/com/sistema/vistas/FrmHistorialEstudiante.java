//Boton Buscar historial del estudiante
    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
       String carnet = txtCarnet.getText().trim();
        
        if (carnet.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingresa un carnet.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 1. Buscar al estudiante para obtener su nombre
        Estudiante est = ctrlEstudiante.buscarEstudiante(carnet);
        if (est == null) {
            JOptionPane.showMessageDialog(this, "El estudiante con carnet " + carnet + " no existe.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // 2. Limpiar la tabla
        DefaultTableModel modelo = (DefaultTableModel) tablaHistorial.getModel();
        modelo.setRowCount(0);

        // 3. Buscar todas las asistencias de ESE estudiante en ESTE curso
        List<Asistencia> todasLasAsistencias = ctrlAsistencia.listarAsistencias();
        int registrosEncontrados = 0;

        for (Asistencia a : todasLasAsistencias) {
            // Filtramos por carnet y por el curso actual
            if (a.getCarnetEstudiante().equals(carnet) && 
                a.getCodigoCurso().equals(cursoSeleccionado.getCodigoCurso())) {
                
                Object[] fila = new Object[3];
                fila[0] = est.getNombre() + " " + est.getApellido(); // Nombre completo
                fila[1] = a.getFecha();
                fila[2] = a.getEstado();
                modelo.addRow(fila);
                registrosEncontrados++;
            }
        }

        if (registrosEncontrados == 0) {
            JOptionPane.showMessageDialog(this, "El estudiante no tiene registros de asistencia en este curso.", "Información", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarActionPerformed
