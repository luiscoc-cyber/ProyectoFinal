//Boton para guardar la asistencia 
    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
          if (tablaAsistencia.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "No hay estudiantes en la tabla.");
        return;
    }

    String fecha = txtFecha.getText();
    boolean exitoTotal = true;

    // Recorremos la tabla fila por fila
    for (int i = 0; i < tablaAsistencia.getRowCount(); i++) {
        String carnet = tablaAsistencia.getValueAt(i, 0).toString();
        String estado = tablaAsistencia.getValueAt(i, 2).toString();
        
        // Generamos un ID único para cada asistencia (ej. A-4F2D)
        String idAsistencia = "A-" + UUID.randomUUID().toString().substring(0, 4).toUpperCase();
        
        // Llamamos a tu controlador
        boolean guardado = ctrlAsistencia.registrarAsistencia(idAsistencia, carnet, cursoSeleccionado.getCodigoCurso(), fecha, estado);
        if (!guardado) {
            exitoTotal = false;
        }
    }

    if (exitoTotal) {
        JOptionPane.showMessageDialog(this, "¡Asistencia guardada correctamente!");
    } else {
        JOptionPane.showMessageDialog(this, "Error: estudiante ya registrado en asistencia");
    }
    
    }//GEN-LAST:event_btnGuardarActionPerformed
