    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        // TODO add your handling code here:
            //1. Obtener los datos de la interfaz
            String usuario = txtUsuario.getText();
            String password = new String(txtPassword.getPassword());
            
            ControladorAutenticacion auth = new ControladorAutenticacion();
            
            String resultado = auth.autenticar(usuario, password);
            
            if (resultado.equals("EXITO")) {
                if (usuario.trim().equalsIgnoreCase("admin")) {
                    JOptionPane.showMessageDialog(this, "Bienvenido Administrador");
            
                    FrmAdminDashboard admin = new FrmAdminDashboard();
                    admin.setVisible(true);
                    this.dispose();
                    
                } else {
                    Profesor profeLogueado = auth.getProfesorLogueado();
                    JOptionPane.showMessageDialog(this, "Bienvenido Profesor: " + profeLogueado.getNombre());
                    
                    FrmMenuProfesor menuProfe = new FrmMenuProfesor(profeLogueado);
                    menuProfe.setVisible(true);
                    this.dispose();
                }
            }else{
                JOptionPane.showMessageDialog(this, resultado, "Error de Autenticación", JOptionPane.ERROR_MESSAGE);
                txtPassword.setText("");
            }
    }//GEN-LAST:event_btnIngresarActionPerformed

